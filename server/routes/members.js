import { Router } from 'express';
import { requireAuth } from '../middleware/auth.js';
import * as controller from '../controllers/members.js';
const router = Router();
router.get('/', requireAuth, controller.list);
router.get('/me/events', requireAuth, controller.myEvents);
router.get('/me/notes', requireAuth, controller.myNotes);
router.get('/:id/records', requireAuth, controller.records);
router.patch('/me', requireAuth, controller.updateMe);
router.delete('/me', requireAuth, controller.deleteMe);
export default router;
